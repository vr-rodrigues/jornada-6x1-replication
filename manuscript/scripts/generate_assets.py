def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def read(path, kind="json"):
    path = Path(path)
    SOURCES[str(path.relative_to(PAPER.parent))] = sha(path)
    return json.loads(path.read_text(encoding="utf-8-sig")) if kind == "json" else pd.read_csv(path)

def dump(path, value):
    Path(path).write_text(json.dumps(value, indent=2, ensure_ascii=False), encoding="utf-8")

def fmt(value, digits=2, signed=False):
    if pd.isna(value): return "--"
    if abs(float(value)) < .5 * 10**(-digits): value = 0.
    return (f"{value:+.{digits}f}" if signed else f"{value:.{digits}f}").replace(".", ",")

def series(axis):
    axis.spines[["right", "top"]].set_visible(False)
    axis.grid(axis="y", alpha=.18, linewidth=.6)
    axis.set_axisbelow(True)
    axis.yaxis.set_major_formatter(FuncFormatter(lambda x, pos: fmt(x, 1)))

def savefig(fig, out, name):
    # Preserve the plots and numerical series, applying the journal font.
    from matplotlib.text import Text
    for item in fig.findobj(match=Text):
        item.set_fontfamily("Times New Roman")
        if item.get_fontweight() in ("bold", "heavy", 700, 800):
            item.set_fontweight("normal")
            item.set_fontstyle("italic")
    for ext in ("pdf", "png"):
        fig.savefig(out / f"{name}.{ext}", dpi=190, bbox_inches="tight",
                    metadata={"Creator": "PAPER/scripts/generate_assets.py"})
    plt.close(fig)

def table(out, filename, label, caption, headers, rows, note, aligns=None):
    n = len(headers)
    lines = [r"% Generated by scripts/generate_assets.py; do not edit.",
             r"\begin{table}[!htbp]", r"\centering", r"\normalsize",
             r"\caption{" + caption + r"}\label{" + label + "}",
             r"\setlength{\tabcolsep}{4pt}",
             r"\begin{tabular}{" + (aligns or "l" + "r"*(n-1)) + "}",
             r"\toprule", " & ".join(headers) + r" \\", r"\midrule"]
    for row in rows:
        if isinstance(row, str):
            lines += [r"\addlinespace", r"\multicolumn{" + str(n) + r"}{l}{\textit{" + row + r"}} \\", r"\addlinespace"]
        else: lines.append(" & ".join(map(str, row)) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\par\smallskip",
              r"\begin{minipage}{0.98\linewidth}\normalsize " + note + r"\end{minipage}",
              r"\end{table}", ""]
    (out / filename).write_text("\n".join(lines), encoding="utf-8")

def check_run(run):
    manifest = read(run / "RUN_MANIFEST.json")
    if manifest["status"] != "complete":
        raise ValueError("Refusing an incomplete run")
    # Fail if archived results or the shared code changed after their audited run.
    checked = 0
    for relative, expected in manifest["output_hashes"].items():
        path = run / relative.replace("\\", "/")
        if not path.is_file() or sha(path) != expected:
            raise ValueError(f"Archived output differs from run manifest: {relative}")
        checked += 1
    for relative, expected in manifest["code_hashes"].items():
        path = REPLICATION / relative.replace("\\", "/")
        if not path.is_file() or sha(path) != expected:
            raise ValueError(f"Model code differs from audited run: {relative}")
    return checked

def curves(run, out, national):
    sys.path.insert(0, str(REPLICATION))
    from src.model.simulation import run_simulation
    from src.calibration.corrected_pipeline import result_row
    rows = []
    anchor_errors = []
    for folder, mapping, version in [
        ("national_empirical", "habitual_integral", "reprocessed_data"),
        ("national_empirical_topcode44", "habitual_limitada44", "reprocessed_topcoded44")]:
        inputs = read(run / folder / "INPUTS.json")
        bridges = read(run / folder / "BRIDGE.json")
        for bridge in bridges:
            mode = bridge["efficiency_mode"]
            for cap in np.arange(30, 44.001, .25):
                targets = deepcopy(inputs["targets"])
                targets["H1"]["value"] = float(cap)
                sim = run_simulation(targets, sigma_sub=bridge["sigma_sub"], omega=bridge["omega"],
                    theta=inputs["theta"], group_specs=inputs["group_specs"], efficiency_mode=mode,
                    hours_bins=inputs["hours_bins"], share_basis=inputs["share_basis"],
                    resource_costs=inputs["resource_costs"])
                row = result_row(sim, version, float(cap), mode, mapping=mapping)
                row["baseline_operator_h0"] = targets["H0"]["value"]
                row["restoration_residual"] = sim["A_req_details"]["relative_error"]
                rows.append(row)
                if cap in (36, 40):
                    old = national.query("version == @version and efficiency_mode == @mode and hours_cap == @cap").iloc[0]
                    for key in ["dY_pct","A_req_pct","A_req_frozen_pct","dGHH_pct","CE_pct","informality_pct"]:
                        anchor_errors.append(abs(row[key] - old[key]))
    if max(anchor_errors) > 1.e-8:
        raise ValueError(f"Recomputed curves fail canonical anchors: {max(anchor_errors)}")
    df = pd.DataFrame(rows)
    reference = df.loc[df.version.eq(PRIMARY_VERSION) & df.hours_cap.eq(PRIMARY_H0)]
    identity_keys = ['dY_pct','A_req_pct','A_req_frozen_pct','dGHH_pct','CE_pct','dInf_pp']
    identity_errors = {key:float(reference[key].abs().max()) for key in identity_keys}
    if len(reference)!=2 or max(identity_errors.values())>1.e-9:
        raise ValueError(f'The 44h reference is not an identity: {identity_errors}')
    dump(out/'reference_44_checks.json',{'status':'passed','baseline_operator_h0':PRIMARY_H0,
        'version':PRIMARY_VERSION,'errors':identity_errors,
        'method':'Recomputed with identical baseline and counterfactual hours; no shift of plotted values'})
    df.to_csv(out/"curves_national.csv", index=False, encoding="utf-8-sig")
    return df, max(anchor_errors)

