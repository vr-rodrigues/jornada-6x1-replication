def make_decomposition(primary,out,details):
    level_rows=[]
    level_records=[]
    for mode in MODES:
        for h in [40,36]:
            decomposition=details[f"{mode}_{h}"]["decomposition"]
            levels=decomposition["levels"]
            ordered=[levels[k] for k in ["baseline","physical_hours","efficiency","reallocation"]]
            reconstructed=100.*(ordered[-1]-ordered[0])/ordered[0]
            if abs(reconstructed-decomposition["total_pct"])>1.e-10:
                raise ValueError("Intermediate decomposition levels do not reproduce output change")
            level_records.append(dict(efficiency_mode=mode,hours_cap=h,
                Y0=ordered[0],YH=ordered[1],YE=ordered[2],Y1=ordered[3],
                denominator="Y0",order="physical_hours;efficiency;formal_informal_reallocation"))
            level_rows.append([MODE_SHORT[mode],f"{h}h"]+[fmt(value,6) for value in ordered])
    pd.DataFrame(level_records).to_csv(out/"decomposition_levels.csv",index=False,encoding="utf-8-sig")
    table(out,"tab_decomposition_levels.tex","tab:decomposition_levels",
          "Níveis intermediários do produto na decomposição nacional",
          ["Função","Teto",r"$Y_0$",r"$Y_H$",r"$Y_E$",r"$Y_1$"],level_rows,
          r"Fonte: simulações nacionais com PNAD 2024T4, base formal limitada a 44h e ponte horária recalibrada. "
          r"Produto em unidades normalizadas do modelo, com seis casas decimais; não em reais. "
          r"A ordem é horas físicas, eficiência e realocação formal--informal: $Y_H$ altera somente as horas, "
          r"$Y_E$ atualiza também a eficiência, mantendo a composição inicial, e $Y_1$ permite a reotimização. "
          r"As contribuições percentuais são $100(Y_H-Y_0)/Y_0$, $100(Y_E-Y_H)/Y_0$ e "
          r"$100(Y_1-Y_E)/Y_0$, cuja soma é $100(Y_1-Y_0)/Y_0$. "
          r"Os cálculos e o CSV usam precisão integral; diferenças aparentes após arredondamento não são resíduos econômicos.",
          aligns="llrrrr")
    records=[]
    for h in [40,36]:
        for mode in MODES:
            r=primary.query("efficiency_mode == @mode and hours_cap == @h").iloc[0]
            record={"mode":mode,"cap":h,
                    **{key:float(r[key]) for key in ["hours_pct","efficiency_pct","reallocation_pct"]},
                    "total_pct":float(r.dY_pct)}
            if abs(sum(record[key] for key in ["hours_pct","efficiency_pct","reallocation_pct"])-record["total_pct"])>1e-9:
                raise ValueError("Decomposition contributions do not sum to the total")
            records.append(record)
    from original_appendix_figures import plot_decomposition
    savefig(plot_decomposition(primary),out,"fig_decomposition")
    pd.DataFrame(records).to_csv(out/"decomposition.csv",index=False,encoding="utf-8-sig")


def make_tfp(primary, out):
    path=REPLICATION/"data_raw/fred/RTFPNABRA632NRUG_pwt110.csv"
    d=read(path,"csv").rename(columns={"RTFPNABRA632NRUG":"rtfpna"})
    d["year"]=pd.to_datetime(d["observation_date"]).dt.year
    if d.year.max()!=2023 or abs(float(d.query("year == 2021").rtfpna.iloc[0])-1)>1e-8:
        raise ValueError("Unexpected PWT vintage")
    values=d.set_index("year").rtfpna
    def growth(a,b):return 100*((values[b]/values[a])**(1/(b-a))-1)
    periods=[(1990,2023),(1990,2019),(2000,2010),(2010,2023)]
    rolling=[(a,a+10,growth(a,a+10)) for a in range(1990,2010)]
    best=max(rolling,key=lambda x:x[2])
    hist=[{"start":a,"end":b,"growth_pct_year":growth(a,b)} for a,b in periods]
    pd.DataFrame(hist).to_csv(out/"tfp_history_rates.csv",index=False,encoding="utf-8-sig")
    d.to_csv(out/"tfp_history.csv",index=False,encoding="utf-8-sig")
    rows=[];table_rows=[]
    for mode in MODES:
        for h in [40,36]:
            r=primary.query("efficiency_mode == @mode and hours_cap == @h").iloc[0]
            gains=[100*((1+r.A_req_pct/100)**(1/t)-1) for t in [3,5,10]]
            rows.append(dict(mode=mode,hours_cap=h,A_req_pct=r.A_req_pct,
                             **{f"annual_gain_{t}yr_pct":v for t,v in zip([3,5,10],gains)}))
